export const GROUPS = [...new Set(CATEGORIES.flatMap(([, , group]) => (group ? [group] : [])))].sort();

// Resolve a personal-finance group name case-insensitively, so a typo fails loudly
// instead of silently matching nothing.
export function resolveGroup(name: string | undefined) {
	if (name === undefined) return undefined;
	const match = GROUPS.find((g) => g.toLowerCase() === name.trim().toLowerCase());
	if (!match) throw new Error(`Unknown category group "${name}". Use one of: ${GROUPS.join(", ")}.`);
	return match;
}
